        f"- affine YBE tables: `{counts['affine_ybe_table_count']}`;",
        f"- failed bidegeneracy: `{counts['bidegenerate_failed']}`;",
        f"- failed noninvolutivity: `{counts['noninvolutive_failed']}`;",
        "- bidegenerate noninvolutive rows before flip testing: "
        f"`{counts['terminal_without_flip_count']}`;",
        f"- failed observer-rigidity: `{counts['observer_failed']}`;",
        f"- observer-rigid rows: `{counts['observer_rigid']}`;",
        f"- failed subsolution-rigidity: `{counts['subsolution_failed']}`;",
