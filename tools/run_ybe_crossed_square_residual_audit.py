import json
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ybe_domination import ybe_crossed_square_residual_audit  # noqa: E402


OUT_JSON = ROOT / "proofs" / "ybe_crossed_square_residual_audit.json"
OUT_MD = ROOT / "proofs" / "ybe_crossed_square_residual_audit.md"


def build_report():
    audit = ybe_crossed_square_residual_audit()
    report = asdict(audit)
    report["case_keys"] = audit.case_keys
    report["records_crossed_square_residual_criterion"] = (
        audit.records_crossed_square_residual_criterion
    )
    OUT_JSON.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    OUT_MD.write_text(render_markdown(report), encoding="utf-8")
    return report


