        "This generated audit records the crossed-square algebra behind the",
        "residual double-deletion quotient from the Brunnian derivative gate.",
        "The quotient is not just a loose remainder: it has a boundary part and",
        "a Moore-Peiffer cycle part.  A positive finite-operator proof must kill",
        "both, while a counterexample must leave one of them nonzero after",
        "edge degeneracies, Peiffer mutual terms, and fixed-base pullback are",
        "removed.",
        "",
        "## Flags",
        "",
        (
            "- crossed-square model identified: "
            f"`{report['crossed_square_model_identified']}`;"
        ),
        (
            "- edge-degenerate subgroup identified: "
            f"`{report['edge_degenerate_subgroup_identified']}`;"
        ),
        (
            "- Peiffer mutual subgroup identified: "
            f"`{report['peiffer_mutual_subgroup_identified']}`;"
        ),
        (
            "- fixed-base pullback subgroup identified: "
            f"`{report['fixed_base_pullback_subgroup_identified']}`;"
        ),
        (
            "- residual exact sequence recorded: "
            f"`{report['residual_exact_sequence_recorded']}`;"
        ),
        (
            "- boundary obstruction identified: "
            f"`{report['boundary_obstruction_identified']}`;"
        ),
        (
            "- Moore-Peiffer obstruction identified: "
            f"`{report['moore_peiffer_obstruction_identified']}`;"
        ),
        (
            "- Peiffer-complete vanishing theorem recorded: "
            f"`{report['peiffer_complete_vanishing_theorem_recorded']}`;"
        ),
        (
            "- obstruction invariant form recorded: "
            f"`{report['obstruction_invariant_form_recorded']}`;"
        ),
        (
            "- records crossed-square residual criterion: "
            f"`{report['records_crossed_square_residual_criterion']}`."
        ),
        "",
        "## Formulas",
        "",
        f"- crossed-square vertices: `{tuple(report['crossed_square_vertices'])}`;",
        f"- residual quotient: `{report['residual_quotient_formula']}`;",
        f"- exact sequence: `{report['exact_sequence_formula']}`;",
        f"- boundary obstruction: `{report['boundary_obstruction_formula']}`;",
