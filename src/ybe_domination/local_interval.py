def equality_partition(items: Sequence[FibrePoint]) -> Partition:
    return canonical_partition(frozenset([item]) for item in items)


def universal_partition(items: Sequence[FibrePoint]) -> Partition:
    return (frozenset(items),)


def canonical_partition(blocks: Iterable[Iterable[FibrePoint]]) -> Partition:
    frozen = [frozenset(block) for block in blocks if block]
    return tuple(
        sorted(frozen, key=lambda block: (len(block), tuple(sorted(map(repr, block)))))
    )


def same_block(partition: Partition, a: FibrePoint, b: FibrePoint) -> bool:
    return any(a in block and b in block for block in partition)


def partition_pairs(partition: Partition) -> FrozenSet[Tuple[FibrePoint, FibrePoint]]:
    pairs = set()
    for block in partition:
        for left in block:
            for right in block:
                pairs.add((left, right))
    return frozenset(pairs)


def set_partitions(items: Sequence[FibrePoint]) -> List[Partition]:
    """Enumerate set partitions. Suitable only for small audit examples."""

    ordered = list(items)
    if not ordered:
        return [tuple()]
    first, rest = ordered[0], ordered[1:]
    if not rest:
        return [(frozenset([first]),)]
    out: List[Partition] = []
    for partition in set_partitions(rest):
        out.append(canonical_partition([frozenset([first]), *partition]))
        for i, block in enumerate(partition):
            new_blocks = list(partition)
            new_blocks[i] = block.union([first])
            out.append(canonical_partition(new_blocks))
    unique = []
    seen = set()
    for partition in out:
        if partition not in seen:
            seen.add(partition)
            unique.append(partition)
    return unique


def relation_family_kind(
    interval: "LocalInterval", family: Mapping[Color, Partition]
) -> str:
    equality = all(len(family[color]) == len(interval.fibres[color]) for color in interval.colors)
    universal = all(
        family[color] == universal_partition(interval.fibres[color])
        for color in interval.colors
    )
    if equality:
        return "equality"
    if universal:
        return "universal"
    if any(family[color] == universal_partition(interval.fibres[color]) for color in interval.colors):
        return "semisplit_or_mixed"
    return "proper_mixed"


def readout_kernel_family(
    interval: "LocalInterval",
    labels: ReadoutLabels,
) -> Dict[Color, Partition]:
    """Return fibre partitions induced by equality of finite readout labels."""

    family = {}
    for color in interval.colors:
        if color not in labels:
            raise ValueError(f"missing readout labels for color {color!r}")
        color_labels = labels[color]
        expected = set(interval.fibres[color])
        actual = set(color_labels)
        if actual != expected:
            raise ValueError(f"readout label domain mismatch for color {color!r}")
        blocks_by_label: Dict[ReadoutLabel, List[FibrePoint]] = {}
        for point in interval.fibres[color]:
            blocks_by_label.setdefault(color_labels[point], []).append(point)
        family[color] = canonical_partition(blocks_by_label.values())
    return family


def readout_kernel_audit(
    interval: "LocalInterval",
    labels: ReadoutLabels,
) -> ReadoutKernelAudit:
    """Audit whether finite readout equality is an admissible congruence."""

    family = readout_kernel_family(interval, labels)
    failure = interval.congruence_family_failure(family)
    return ReadoutKernelAudit(
        family=family,
        kind=relation_family_kind(interval, family),
        label_count_rows=tuple(
            (color, len(set(labels[color].values())))
            for color in interval.colors
        ),
        block_count_rows=tuple(
            (color, len(family[color]))
            for color in interval.colors
        ),
        admissible=failure is None,
        failure=failure,
    )


def _meet_partition(left: Partition, right: Partition) -> Partition:
    return canonical_partition(
        left_block.intersection(right_block)
        for left_block in left
        for right_block in right
    )


def _meet_families(
    interval: "LocalInterval",
    families: Sequence[Mapping[Color, Partition]],
) -> Dict[Color, Partition]:
    if not families:
        raise ValueError("at least one family is required")
    current = {color: families[0][color] for color in interval.colors}
    for family in families[1:]:
        current = {
            color: _meet_partition(current[color], family[color])
            for color in interval.colors
        }
    return current


def product_readout_labels(
    interval: "LocalInterval",
    *label_families: ReadoutLabels,
) -> Dict[Color, Dict[FibrePoint, Tuple[ReadoutLabel, ...]]]:
    """Return tuple-valued labels combining fixed readout factors."""

    if not label_families:
        raise ValueError("at least one readout label family is required")
    for labels in label_families:
        readout_kernel_family(interval, labels)
    return {
        color: {
            point: tuple(labels[color][point] for labels in label_families)
            for point in interval.fibres[color]
        }
        for color in interval.colors
    }


def product_readout_kernel_audit(
    interval: "LocalInterval",
    *label_families: ReadoutLabels,
) -> ProductReadoutKernelAudit:
    """Audit the kernel of a product of finite readout label systems."""

    factor_audits = tuple(
        readout_kernel_audit(interval, labels)
        for labels in label_families
    )
    product_labels = product_readout_labels(interval, *label_families)
    product_audit = readout_kernel_audit(interval, product_labels)
    meet_family = _meet_families(
        interval,
        tuple(audit.family for audit in factor_audits),
    )
    return ProductReadoutKernelAudit(
        factor_audits=factor_audits,
        product_labels=product_labels,
        product_audit=product_audit,
        meet_family=meet_family,
        product_family_is_factor_meet=product_audit.family == meet_family,
    )


def _partition_block_lookup(partition: Partition) -> Dict[FibrePoint, Block]:
    lookup: Dict[FibrePoint, Block] = {}
    for block in partition:
        for point in block:
            lookup[point] = block
    return lookup


def quotient_interval_by_family(
    interval: "LocalInterval",
    family: Mapping[Color, Partition],
) -> "LocalInterval":
    """Return the local interval quotient by an admissible fibre congruence."""

    if not interval.is_admissible_congruence_family(family):
        raise ValueError("family must be an admissible local congruence")
    lookups = {
        color: _partition_block_lookup(family[color])
        for color in interval.colors
    }
    fibres: Dict[Color, Tuple[Block, ...]] = {
        color: tuple(family[color])
        for color in interval.colors
    }
    table = {}
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]
        for block_x in fibres[a]:
            for block_y in fibres[b]:
                x = next(iter(block_x))
                y = next(iter(block_y))
                u, v = interval.T[(a, b, x, y)]
                table[(a, b, block_x, block_y)] = (
                    lookups[c][u],
                    lookups[d][v],
                )
    return LocalInterval(
        interval.colors,
        fibres,
        interval.base_R,
        table,
    )


def readout_kernel_quotient_interval(
    interval: "LocalInterval",
    labels: ReadoutLabels,
) -> "LocalInterval":
    """Return the quotient interval induced by admissible readout labels."""

    return quotient_interval_by_family(interval, readout_kernel_family(interval, labels))


def _pairs_from_value_fibres(
    domain: Sequence[FibrePoint],
    values_by_input: Mapping[FibrePoint, FibrePoint],
) -> Tuple[Tuple[FibrePoint, FibrePoint], ...]:
    fibres: Dict[FibrePoint, List[FibrePoint]] = {}
    for item in domain:
        fibres.setdefault(values_by_input[item], []).append(item)
    pairs = []
    for block in fibres.values():
        for left in block:
            for right in block:
                if left != right:
                    pairs.append((left, right))
    return tuple(pairs)


def coordinate_kernel_seed_pairs(
    interval: "LocalInterval",
    *,
    include_coretraction_kernels: bool = False,
) -> Dict[Color, Tuple[Tuple[FibrePoint, FibrePoint], ...]]:
    """Return nontrivial coordinate-kernel pairs for a local interval.

    By default this uses the two nondegeneracy coordinate families:
    `y -> pr_1 T(x,y)` and `x -> pr_2 T(x,y)`.  With
    `include_coretraction_kernels=True`, it also includes the dual coordinate
    families `x -> pr_1 T(x,y)` and `y -> pr_2 T(x,y)`.
    """

    pairs: Dict[Color, List[Tuple[FibrePoint, FibrePoint]]] = {
        color: [] for color in interval.colors
    }
    for a, b in product(interval.colors, repeat=2):
        for x in interval.fibres[a]:
            pairs[b].extend(
                _pairs_from_value_fibres(
                    interval.fibres[b],
                    {
                        y: interval.T[(a, b, x, y)][0]
                        for y in interval.fibres[b]
                    },
                )
            )
            if include_coretraction_kernels:
                pairs[b].extend(
                    _pairs_from_value_fibres(
                        interval.fibres[b],
                        {
                            y: interval.T[(a, b, x, y)][1]
                            for y in interval.fibres[b]
                        },
                    )
                )
        for y in interval.fibres[b]:
            pairs[a].extend(
                _pairs_from_value_fibres(
                    interval.fibres[a],
                    {
                        x: interval.T[(a, b, x, y)][1]
                        for x in interval.fibres[a]
                    },
                )
            )
            if include_coretraction_kernels:
                pairs[a].extend(
                    _pairs_from_value_fibres(
                        interval.fibres[a],
                        {
                            x: interval.T[(a, b, x, y)][0]
                            for x in interval.fibres[a]
                        },
                    )
                )
    return {
        color: tuple(sorted(set(color_pairs), key=repr))
        for color, color_pairs in pairs.items()
    }


def generated_admissible_congruence_family(
    interval: "LocalInterval", seed_pairs: PairFamily
) -> Dict[Color, Partition]:
    """Return the least admissible family containing the given seed pairs.

    The closure repeatedly transports related product pairs through every
    coloured bijection `T_{a,b}` and through its inverse.  Since the fibres are
    finite, this reaches the least equivalence-family whose product relations
    are transported exactly by all local tables.
    """

    return dict(generated_admissible_congruence_audit(interval, seed_pairs).family)


def coordinate_kernel_pair_closure_audits(
    interval: "LocalInterval",
    *,
    include_coretraction_kernels: bool = False,
) -> Tuple[CoordinateKernelPairClosureAudit, ...]:
    """Return single-pair closures for coordinate-kernel degeneracies."""

    audits = []
    seed_pairs = coordinate_kernel_seed_pairs(
        interval,
        include_coretraction_kernels=include_coretraction_kernels,
    )
    seen = set()
    for color in interval.colors:
        for left, right in seed_pairs[color]:
            if left == right:
                continue
            key = (color, tuple(sorted((left, right), key=repr)))
            if key in seen:
                continue
            seen.add(key)
            generated = generated_admissible_congruence_audit(
                interval,
                {color: ((left, right),)},
            )
            audits.append(
                CoordinateKernelPairClosureAudit(
                    color=color,
                    left=left,
                    right=right,
                    include_coretraction_kernels=include_coretraction_kernels,
                    generated=generated,
                )
            )
    return tuple(audits)


def coordinate_kernel_pair_closure_failures(
    interval: "LocalInterval",
    *,
    include_coretraction_kernels: bool = False,
) -> Tuple[CoordinateKernelPairClosureAudit, ...]:
    """Return coordinate-kernel pair closures that are not universal."""

    return tuple(
        audit
        for audit in coordinate_kernel_pair_closure_audits(
            interval,
            include_coretraction_kernels=include_coretraction_kernels,
        )
        if audit.generated.kind != "universal"
    )


def continuation_seed_rows(
    interval: "LocalInterval",
) -> Tuple[ContinuationSeedRow, ...]:
    """Return rows where the rack-continuing second output changes state.

    This is meaningful after the base row is in left rack convention, so that
    `base_R(a,b)=(a*b,a)`.  Rows whose second output colour is not `a` are
    reported separately by `continuation_congruence_audit`.
    """

    rows: List[ContinuationSeedRow] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]
        if d != a:
            continue
        for x in interval.fibres[a]:
            for y in interval.fibres[b]:
                _u, v = interval.T[(a, b, x, y)]
                if v != x:
                    rows.append(
                        ContinuationSeedRow(
                            left_color=a,
                            right_color=b,
                            output_left_color=c,
                            output_right_color=d,
                            left_input=x,
                            right_input=y,
                            continuing_output=v,
                        )
                    )
    return tuple(rows)


def continuation_seed_pairs(
    interval: "LocalInterval",
) -> Dict[Color, Tuple[Tuple[FibrePoint, FibrePoint], ...]]:
    """Return seed pairs `x ~ v` forced by non-strand-continuing outputs."""

    pairs: Dict[Color, set[Tuple[FibrePoint, FibrePoint]]] = {
        color: set() for color in interval.colors
    }
    for row in continuation_seed_rows(interval):
        pairs[row.left_color].add((row.left_input, row.continuing_output))
    return {
        color: tuple(sorted(color_pairs, key=repr))
        for color, color_pairs in pairs.items()
    }


def continuation_congruence_audit(
    interval: "LocalInterval",
) -> ContinuationCongruenceAudit:
    """Audit the continuation-change closure used in descent separation."""

    non_rack_base_rows = tuple(
        (a, b, c, d)
        for a, b in product(interval.colors, repeat=2)
        for c, d in (interval.base_R[(a, b)],)
        if d != a
    )
    seed_rows = continuation_seed_rows(interval)
    generated = generated_admissible_congruence_audit(
        interval,
        continuation_seed_pairs(interval),
    )
    return ContinuationCongruenceAudit(
        seed_rows=seed_rows,
        non_rack_base_rows=non_rack_base_rows,
        generated=generated,
    )


def _is_bijection_to(values: Iterable[FibrePoint], codomain: Sequence[FibrePoint]) -> bool:
    values_tuple = tuple(values)
    return len(values_tuple) == len(codomain) and set(values_tuple) == set(codomain)


def section_unit_row_audits(interval: "LocalInterval") -> Tuple[SectionUnitRowAudit, ...]:
    """Return coordinate-section unit data for every coloured local row."""

    audits: List[SectionUnitRowAudit] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]
        left_unit_inputs = []
        left_nonunit_inputs = []
        right_unit_inputs = []
        right_nonunit_inputs = []

        for x in interval.fibres[a]:
            values = (
                interval.T[(a, b, x, y)][0]
                for y in interval.fibres[b]
            )
            if _is_bijection_to(values, interval.fibres[c]):
                left_unit_inputs.append(x)
            else:
                left_nonunit_inputs.append(x)

        for y in interval.fibres[b]:
            values = (
                interval.T[(a, b, x, y)][1]
                for x in interval.fibres[a]
            )
            if _is_bijection_to(values, interval.fibres[d]):
                right_unit_inputs.append(y)
            else:
                right_nonunit_inputs.append(y)

        audits.append(
            SectionUnitRowAudit(
                left_color=a,
                right_color=b,
                output_left_color=c,
                output_right_color=d,
                left_unit_inputs=tuple(left_unit_inputs),
                left_nonunit_inputs=tuple(left_nonunit_inputs),
                right_unit_inputs=tuple(right_unit_inputs),
                right_nonunit_inputs=tuple(right_nonunit_inputs),
            )
        )
    return tuple(audits)


def two_sided_unit_collapse_audit(interval: "LocalInterval") -> TwoSidedUnitCollapseAudit:
    """Classify the two-sided-unit collapse split for a local interval."""

    return TwoSidedUnitCollapseAudit(
        colored_ybe=interval.is_colored_ybe(),
        continuation=continuation_congruence_audit(interval),
        row_audits=section_unit_row_audits(interval),
    )


def section_kernel_companion_audit(
    interval: "LocalInterval",
) -> SectionKernelCompanionAudit:
    """Record companion-output recovery for noninjective coordinate sections."""

    rows: List[SectionKernelCompanionRow] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]

        for x in interval.fibres[a]:
            by_left_output: Dict[FibrePoint, List[Tuple[FibrePoint, FibrePoint]]] = {}
            for y in interval.fibres[b]:
                u, v = interval.T[(a, b, x, y)]
                by_left_output.setdefault(u, []).append((y, v))
            for u, entries in by_left_output.items():
                for (y0, v0), (y1, v1) in combinations(entries, 2):
                    rows.append(
                        SectionKernelCompanionRow(
                            side="left",
                            left_color=a,
                            right_color=b,
                            output_left_color=c,
                            output_right_color=d,
                            fixed_input=x,
                            collapsed_inputs=(y0, y1),
                            common_output=u,
                            companion_outputs=(v0, v1),
                        )
                    )

        for y in interval.fibres[b]:
            by_right_output: Dict[FibrePoint, List[Tuple[FibrePoint, FibrePoint]]] = {}
            for x in interval.fibres[a]:
                u, v = interval.T[(a, b, x, y)]
                by_right_output.setdefault(v, []).append((x, u))
            for v, entries in by_right_output.items():
                for (x0, u0), (x1, u1) in combinations(entries, 2):
                    rows.append(
                        SectionKernelCompanionRow(
                            side="right",
                            left_color=a,
                            right_color=b,
                            output_left_color=c,
                            output_right_color=d,
                            fixed_input=y,
                            collapsed_inputs=(x0, x1),
                            common_output=v,
                            companion_outputs=(u0, u1),
                        )
                    )

    return SectionKernelCompanionAudit(collision_rows=tuple(rows))


def _rank_profile_row(
    *,
    side: str,
    left_color: Color,
    right_color: Color,
    output_left_color: Color,
    output_right_color: Color,
    fixed_input: FibrePoint,
    domain: Sequence[FibrePoint],
    codomain: Sequence[FibrePoint],
    values: Mapping[FibrePoint, FibrePoint],
) -> SectionRankProfileRow:
    by_value: Dict[FibrePoint, List[FibrePoint]] = {}
    for item in domain:
        by_value.setdefault(values[item], []).append(item)
    kernel_blocks = tuple(
        tuple(sorted(block, key=repr))
        for _value, block in sorted(by_value.items(), key=lambda item: repr(item[0]))
    )
    return SectionRankProfileRow(
        side=side,
        left_color=left_color,
        right_color=right_color,
        output_left_color=output_left_color,
        output_right_color=output_right_color,
        fixed_input=fixed_input,
        domain_size=len(domain),
        codomain_size=len(codomain),
        rank=len(by_value),
        kernel_blocks=kernel_blocks,
        image=tuple(sorted(by_value, key=repr)),
    )


def section_rank_profile_collapse_audit(
    interval: "LocalInterval",
) -> SectionRankProfileCollapseAudit:
    """Return rank/kernel profiles for all coordinate sections."""

    rows: List[SectionRankProfileRow] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]
        for x in interval.fibres[a]:
            rows.append(
                _rank_profile_row(
                    side="left",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=x,
                    domain=interval.fibres[b],
                    codomain=interval.fibres[c],
                    values={
                        y: interval.T[(a, b, x, y)][0]
                        for y in interval.fibres[b]
                    },
                )
            )
        for y in interval.fibres[b]:
            rows.append(
                _rank_profile_row(
                    side="right",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=y,
                    domain=interval.fibres[a],
                    codomain=interval.fibres[d],
                    values={
                        x: interval.T[(a, b, x, y)][1]
                        for x in interval.fibres[a]
                    },
                )
            )
    return SectionRankProfileCollapseAudit(rows=tuple(rows))


def _triangular_bundle_fibres(
    *,
    constant_codomain: Sequence[FibrePoint],
    companion_codomain: Sequence[FibrePoint],
    constant_map: Mapping[FibrePoint, FibrePoint],
    companion_images: Mapping[FibrePoint, Tuple[FibrePoint, ...]],
) -> Tuple[TriangularBundleFibre, ...]:
    fibres = []
    for output_value in constant_codomain:
        source_inputs = tuple(
            sorted(
                (
                    source
                    for source, value in constant_map.items()
                    if value == output_value
                ),
                key=repr,
            )
        )
        fibres.append(
            TriangularBundleFibre(
                output_value=output_value,
                source_inputs=source_inputs,
                companion_image_blocks=tuple(
                    (source, companion_images[source])
                    for source in source_inputs
                ),
                companion_codomain=tuple(companion_codomain),
            )
        )
    return tuple(fibres)


def triangular_bundle_audit(interval: "LocalInterval") -> TriangularBundleAudit:
    """Return bundle partitions for constant-section triangular rows."""

    audits: List[TriangularBundleRowAudit] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]

        left_constant = True
        left_constant_map: Dict[FibrePoint, FibrePoint] = {}
        left_companion_images: Dict[FibrePoint, Tuple[FibrePoint, ...]] = {}
        left_companion_injective = True
        for x in interval.fibres[a]:
            outputs = [
                interval.T[(a, b, x, y)]
                for y in interval.fibres[b]
            ]
            left_values = {u for u, _v in outputs}
            if len(left_values) != 1:
                left_constant = False
                break
            left_constant_map[x] = outputs[0][0]
            companion_image = tuple(sorted({v for _u, v in outputs}, key=repr))
            left_companion_images[x] = companion_image
            if len(companion_image) != len(interval.fibres[b]):
                left_companion_injective = False

        if left_constant:
            audits.append(
                TriangularBundleRowAudit(
                    side="left",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    constant_map=tuple(
                        sorted(left_constant_map.items(), key=lambda item: repr(item[0]))
                    ),
                    bundle_fibres=_triangular_bundle_fibres(
                        constant_codomain=interval.fibres[c],
                        companion_codomain=interval.fibres[d],
                        constant_map=left_constant_map,
                        companion_images=left_companion_images,
                    ),
                    companion_sections_injective=left_companion_injective,
                )
            )

        right_constant = True
        right_constant_map: Dict[FibrePoint, FibrePoint] = {}
        right_companion_images: Dict[FibrePoint, Tuple[FibrePoint, ...]] = {}
        right_companion_injective = True
        for y in interval.fibres[b]:
            outputs = [
                interval.T[(a, b, x, y)]
                for x in interval.fibres[a]
            ]
            right_values = {v for _u, v in outputs}
            if len(right_values) != 1:
                right_constant = False
                break
            right_constant_map[y] = outputs[0][1]
            companion_image = tuple(sorted({u for u, _v in outputs}, key=repr))
            right_companion_images[y] = companion_image
            if len(companion_image) != len(interval.fibres[a]):
                right_companion_injective = False

        if right_constant:
            audits.append(
                TriangularBundleRowAudit(
                    side="right",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    constant_map=tuple(
                        sorted(right_constant_map.items(), key=lambda item: repr(item[0]))
                    ),
                    bundle_fibres=_triangular_bundle_fibres(
                        constant_codomain=interval.fibres[d],
                        companion_codomain=interval.fibres[c],
                        constant_map=right_constant_map,
                        companion_images=right_companion_images,
                    ),
                    companion_sections_injective=right_companion_injective,
                )
            )

    return TriangularBundleAudit(row_audits=tuple(audits))


def triangular_recovery_audit(interval: "LocalInterval") -> TriangularRecoveryAudit:
    """Return inverse recovery tables for constant-section triangular rows."""

    audits: List[TriangularRecoveryRowAudit] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]

        left_constant_map: Dict[FibrePoint, FibrePoint] = {}
        left_companion_preimages: Dict[FibrePoint, Dict[FibrePoint, FibrePoint]] = {}
        left_constant = True
        for x in interval.fibres[a]:
            outputs = [
                (y, *interval.T[(a, b, x, y)])
                for y in interval.fibres[b]
            ]
            left_values = {u for _y, u, _v in outputs}
            if len(left_values) != 1:
                left_constant = False
                break
            left_constant_map[x] = next(iter(left_values))
            preimage: Dict[FibrePoint, FibrePoint] = {}
            for y, _u, v in outputs:
                preimage[v] = y
            left_companion_preimages[x] = preimage

        if left_constant:
            entries: List[TriangularRecoveryEntry] = []
            failures: List[Tuple[FibrePoint, FibrePoint]] = []
            for u, v in product(interval.fibres[c], interval.fibres[d]):
                candidates = [
                    (x, left_companion_preimages[x][v])
                    for x in interval.fibres[a]
                    if left_constant_map[x] == u
                    and v in left_companion_preimages[x]
                ]
                if len(candidates) != 1:
                    failures.append((u, v))
                    continue
                x, y = candidates[0]
                entries.append(
                    TriangularRecoveryEntry(
                        output_left=u,
                        output_right=v,
                        recovered_left_input=x,
                        recovered_right_input=y,
                    )
                )
            audits.append(
                TriangularRecoveryRowAudit(
                    side="left",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    source_size=len(interval.fibres[a]) * len(interval.fibres[b]),
                    output_size=len(interval.fibres[c]) * len(interval.fibres[d]),
                    entries=tuple(entries),
                    missing_or_ambiguous_outputs=tuple(failures),
                )
            )

        right_constant_map: Dict[FibrePoint, FibrePoint] = {}
        right_companion_preimages: Dict[FibrePoint, Dict[FibrePoint, FibrePoint]] = {}
        right_constant = True
        for y in interval.fibres[b]:
            outputs = [
                (x, *interval.T[(a, b, x, y)])
                for x in interval.fibres[a]
            ]
            right_values = {v for _x, _u, v in outputs}
            if len(right_values) != 1:
                right_constant = False
                break
            right_constant_map[y] = next(iter(right_values))
            preimage = {}
            for x, u, _v in outputs:
                preimage[u] = x
            right_companion_preimages[y] = preimage

        if right_constant:
            entries = []
            failures = []
            for u, v in product(interval.fibres[c], interval.fibres[d]):
                candidates = [
                    (right_companion_preimages[y][u], y)
                    for y in interval.fibres[b]
                    if right_constant_map[y] == v
                    and u in right_companion_preimages[y]
                ]
                if len(candidates) != 1:
                    failures.append((u, v))
                    continue
                x, y = candidates[0]
                entries.append(
                    TriangularRecoveryEntry(
                        output_left=u,
                        output_right=v,
                        recovered_left_input=x,
                        recovered_right_input=y,
                    )
                )
            audits.append(
                TriangularRecoveryRowAudit(
                    side="right",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    source_size=len(interval.fibres[a]) * len(interval.fibres[b]),
                    output_size=len(interval.fibres[c]) * len(interval.fibres[d]),
                    entries=tuple(entries),
                    missing_or_ambiguous_outputs=tuple(failures),
                )
            )

    return TriangularRecoveryAudit(row_audits=tuple(audits))


def triangular_column_collapse_audit(
    interval: "LocalInterval",
) -> TriangularColumnCollapseAudit:
    """Classify triangular rows by opposite-column kernel type.

    A left triangular row has first output independent of the right input:
    `T(x,y)=(alpha(x), beta_x(y))`.  Its opposite columns are the maps
    `x -> beta_x(y)`.  The right-side dual is audited symmetrically.
    """

    audits: List[TriangularColumnCollapseRowAudit] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]

        left_constant = True
        left_constant_map: Dict[FibrePoint, FibrePoint] = {}
        for x in interval.fibres[a]:
            outputs = [
                interval.T[(a, b, x, y)]
                for y in interval.fibres[b]
            ]
            left_values = {u for u, _v in outputs}
            if len(left_values) != 1:
                left_constant = False
                break
            left_constant_map[x] = outputs[0][0]

        if left_constant:
            companion_sections = tuple(
                _rank_profile_row(
                    side="left-companion",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=x,
                    domain=interval.fibres[b],
                    codomain=interval.fibres[d],
                    values={
                        y: interval.T[(a, b, x, y)][1]
                        for y in interval.fibres[b]
                    },
                )
                for x in interval.fibres[a]
            )
            opposite_sections = tuple(
                _rank_profile_row(
                    side="left-opposite",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=y,
                    domain=interval.fibres[a],
                    codomain=interval.fibres[d],
                    values={
                        x: interval.T[(a, b, x, y)][1]
                        for x in interval.fibres[a]
                    },
                )
                for y in interval.fibres[b]
            )
            audits.append(
                TriangularColumnCollapseRowAudit(
                    side="left",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    constant_codomain=tuple(interval.fibres[c]),
                    constant_map=tuple(
                        sorted(left_constant_map.items(), key=lambda item: repr(item[0]))
                    ),
                    companion_sections=companion_sections,
                    opposite_sections=opposite_sections,
                )
            )

        right_constant = True
        right_constant_map: Dict[FibrePoint, FibrePoint] = {}
        for y in interval.fibres[b]:
            outputs = [
                interval.T[(a, b, x, y)]
                for x in interval.fibres[a]
            ]
            right_values = {v for _u, v in outputs}
            if len(right_values) != 1:
                right_constant = False
                break
            right_constant_map[y] = outputs[0][1]

        if right_constant:
            companion_sections = tuple(
                _rank_profile_row(
                    side="right-companion",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=y,
                    domain=interval.fibres[a],
                    codomain=interval.fibres[c],
                    values={
                        x: interval.T[(a, b, x, y)][0]
                        for x in interval.fibres[a]
                    },
                )
                for y in interval.fibres[b]
            )
            opposite_sections = tuple(
                _rank_profile_row(
                    side="right-opposite",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    fixed_input=x,
                    domain=interval.fibres[b],
                    codomain=interval.fibres[c],
                    values={
                        y: interval.T[(a, b, x, y)][0]
                        for y in interval.fibres[b]
                    },
                )
                for x in interval.fibres[a]
            )
            audits.append(
                TriangularColumnCollapseRowAudit(
                    side="right",
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    constant_codomain=tuple(interval.fibres[d]),
                    constant_map=tuple(
                        sorted(right_constant_map.items(), key=lambda item: repr(item[0]))
                    ),
                    companion_sections=companion_sections,
                    opposite_sections=opposite_sections,
                )
            )

    return TriangularColumnCollapseAudit(row_audits=tuple(audits))


def _section_domain_color(section: SectionRankProfileRow) -> Color:
    if section.side in ("left-companion", "right-opposite"):
        return section.right_color
    if section.side in ("left-opposite", "right-companion"):
        return section.left_color
    raise ValueError(f"unknown triangular section side {section.side!r}")


def _kernel_edge_pairs(
    blocks: Iterable[Iterable[FibrePoint]],
) -> Tuple[Tuple[FibrePoint, FibrePoint], ...]:
    pairs = []
    for block in blocks:
        for left, right in combinations(tuple(block), 2):
            pairs.append(tuple(sorted((left, right), key=repr)))
    return tuple(sorted(set(pairs), key=repr))


def triangular_latin_defect_closure_audit(
    interval: "LocalInterval",
) -> TriangularLatinDefectClosureAudit:
    """Close non-Latin triangular kernel edges under admissible congruence.

    Proper closures are incompatible with a genuinely local-minimal remaining
    interval.  Universal closures identify the exact seed edges that still need
    fixed detector routing.
    """

    rows: List[TriangularLatinDefectClosureRow] = []
    for row in triangular_column_collapse_audit(interval).row_audits:
        if row.latin_unit_triangular:
            continue

        constant_domain = row.left_color if row.side == "left" else row.right_color
        for left, right in _kernel_edge_pairs(row.constant_kernel_blocks):
            rows.append(
                TriangularLatinDefectClosureRow(
                    side=row.side,
                    defect="constant_map_kernel",
                    left_color=row.left_color,
                    right_color=row.right_color,
                    domain_color=constant_domain,
                    fixed_input=None,
                    collapsed_inputs=(left, right),
                    generated=generated_admissible_congruence_audit(
                        interval,
                        {constant_domain: ((left, right),)},
                    ),
                )
            )

        for section in row.companion_sections:
            domain_color = _section_domain_color(section)
            for left, right in _kernel_edge_pairs(section.kernel_blocks):
                rows.append(
                    TriangularLatinDefectClosureRow(
                        side=row.side,
                        defect="companion_section_kernel",
                        left_color=row.left_color,
                        right_color=row.right_color,
                        domain_color=domain_color,
                        fixed_input=section.fixed_input,
                        collapsed_inputs=(left, right),
                        generated=generated_admissible_congruence_audit(
                            interval,
                            {domain_color: ((left, right),)},
                        ),
                    )
                )

        for section in row.opposite_sections:
            domain_color = _section_domain_color(section)
            for left, right in _kernel_edge_pairs(section.kernel_blocks):
                rows.append(
                    TriangularLatinDefectClosureRow(
                        side=row.side,
                        defect="opposite_section_kernel",
                        left_color=row.left_color,
                        right_color=row.right_color,
                        domain_color=domain_color,
                        fixed_input=section.fixed_input,
                        collapsed_inputs=(left, right),
                        generated=generated_admissible_congruence_audit(
                            interval,
                            {domain_color: ((left, right),)},
                        ),
                    )
                )

    return TriangularLatinDefectClosureAudit(rows=tuple(rows))


def triangular_constant_kernel_recovery_route_audit(
    interval: "LocalInterval",
) -> TriangularConstantKernelRecoveryRouteAudit:
    """Route constant-map kernel edges to the triangular recovery table."""

    recovery_rows = {
        (row.side, row.left_color, row.right_color): row
        for row in triangular_recovery_audit(interval).row_audits
    }
    rows = []
    for closure in triangular_latin_defect_closure_audit(interval).rows:
        if closure.defect != "constant_map_kernel":
            continue
        recovery = recovery_rows.get(
            (closure.side, closure.left_color, closure.right_color)
        )
        witnesses = []
        for input_value in closure.collapsed_inputs:
            if recovery is None:
                output_pairs: Tuple[Tuple[FibrePoint, FibrePoint], ...] = ()
            elif closure.side == "left":
                output_pairs = tuple(
                    (entry.output_left, entry.output_right)
                    for entry in recovery.entries
                    if entry.recovered_left_input == input_value
                )
            else:
                output_pairs = tuple(
                    (entry.output_left, entry.output_right)
                    for entry in recovery.entries
                    if entry.recovered_right_input == input_value
                )
            witnesses.append((input_value, output_pairs))

        rows.append(
            TriangularConstantKernelRecoveryRouteRow(
                side=closure.side,
                left_color=closure.left_color,
                right_color=closure.right_color,
                domain_color=closure.domain_color,
                collapsed_inputs=closure.collapsed_inputs,
                closure_kind=closure.closure_kind,
                recovery_row_present=recovery is not None,
                recovery_formula_bijective=(
                    recovery.recovery_formula_bijective if recovery is not None else False
                ),
                witness_output_pairs=tuple(witnesses),
            )
        )

    return TriangularConstantKernelRecoveryRouteAudit(rows=tuple(rows))


def missing_triangular_row_profile_audit(
    interval: "LocalInterval",
) -> MissingTriangularRowProfileAudit:
    """Explain sides that do not have constant-section triangular form."""

    column_rows = {
        (row.side, row.left_color, row.right_color)
        for row in triangular_column_collapse_audit(interval).row_audits
    }
    rank_rows = section_rank_profile_collapse_audit(interval).rows
    rows: List[MissingTriangularRowProfile] = []
    for a, b in product(interval.colors, repeat=2):
        c, d = interval.base_R[(a, b)]
        for side in ("left", "right"):
            if (side, a, b) in column_rows:
                continue
            section_profiles = tuple(
                row
                for row in rank_rows
                if row.side == side and row.left_color == a and row.right_color == b
            )
            rows.append(
                MissingTriangularRowProfile(
                    side=side,
                    left_color=a,
                    right_color=b,
                    output_left_color=c,
                    output_right_color=d,
                    section_profiles=section_profiles,
                )
            )
    return MissingTriangularRowProfileAudit(rows=tuple(rows))


def missing_triangular_left_rack_cardinality_audit(
    interval: "LocalInterval",
) -> MissingTriangularLeftRackCardinalityAudit:
    """Close injective-nonsurjective missing profiles over a left rack base."""

    continuation = continuation_congruence_audit(interval)
    profile = missing_triangular_row_profile_audit(interval)
    section_rows = tuple(
        section
        for row in profile.rows
        for section in row.section_profiles
    )
    unequal_rows = tuple(
        section
        for section in section_rows
        if section.domain_size != section.codomain_size
    )
    return MissingTriangularLeftRackCardinalityAudit(
        continuation=continuation,
        profile=profile,
        unequal_section_rows=unequal_rows,
    )


def missing_triangular_coordinate_unit_routing_audit(
    interval: "LocalInterval",
) -> MissingTriangularCoordinateUnitRoutingAudit:
    """Route coordinate-unit missing triangular rows to closed/mixed branches."""

    profile = missing_triangular_row_profile_audit(interval)
    profile_by_side = {
        (row.side, row.left_color, row.right_color): row for row in profile.rows
    }
    triangular_sides = {
        (row.side, row.left_color, row.right_color)
        for row in triangular_column_collapse_audit(interval).row_audits
    }
    unit_rows = {
        (row.left_color, row.right_color): row
        for row in section_unit_row_audits(interval)
    }
    unit_collapse = two_sided_unit_collapse_audit(interval)

    coordinate_unit_sides: Dict[Tuple[Color, Color], List[str]] = {}
    for row in profile.coordinate_unit_rows:
        coordinate_unit_sides.setdefault((row.left_color, row.right_color), []).append(
            row.side
        )

    def side_explanation(side: str, left: Color, right: Color) -> str:
        row = profile_by_side.get((side, left, right))
        if row is not None:
            return row.explanation
        if (side, left, right) in triangular_sides:
            return "triangular_row_present"
        return "missing_side_profile_absent"

    rows: List[MissingTriangularCoordinateUnitRoute] = []
    for (a, b), sides in sorted(
        coordinate_unit_sides.items(), key=lambda item: (repr(item[0][0]), repr(item[0][1]))
    ):
        c, d = interval.base_R[(a, b)]
        unit_row = unit_rows[(a, b)]
        rows.append(
            MissingTriangularCoordinateUnitRoute(
                left_color=a,
                right_color=b,
                output_left_color=c,
                output_right_color=d,
                coordinate_unit_sides=tuple(
                    side for side in ("left", "right") if side in set(sides)
                ),
                left_explanation=side_explanation("left", a, b),
                right_explanation=side_explanation("right", a, b),
                left_unit_inputs=unit_row.left_unit_inputs,
                left_nonunit_inputs=unit_row.left_nonunit_inputs,
                right_unit_inputs=unit_row.right_unit_inputs,
                right_nonunit_inputs=unit_row.right_nonunit_inputs,
            )
        )

    return MissingTriangularCoordinateUnitRoutingAudit(
        colored_ybe=interval.is_colored_ybe(),
        locally_nondegenerate_closed_branch=(
            unit_collapse.locally_nondegenerate_closed_branch
        ),
        rows=tuple(rows),
    )


