@dataclass(frozen=True)
class TriangularBundleFibre:
    """One fibre of a constant-output triangular row."""

    output_value: FibrePoint
    source_inputs: Tuple[FibrePoint, ...]
    companion_image_blocks: Tuple[Tuple[FibrePoint, Tuple[FibrePoint, ...]], ...]
    companion_codomain: Tuple[FibrePoint, ...]

    @property
    def block_sizes(self) -> Tuple[int, ...]:
        return tuple(len(block) for _source, block in self.companion_image_blocks)

    @property
    def blocks_are_disjoint(self) -> bool:
        seen = set()
        for _source, block in self.companion_image_blocks:
            block_set = set(block)
            if seen.intersection(block_set):
                return False
            seen.update(block_set)
        return True

    @property
    def blocks_cover_companion_codomain(self) -> bool:
        union = {
            value
            for _source, block in self.companion_image_blocks
            for value in block
        }
        return union == set(self.companion_codomain)

    @property
    def blocks_partition_companion_codomain(self) -> bool:
        return self.blocks_are_disjoint and self.blocks_cover_companion_codomain


@dataclass(frozen=True)
class TriangularBundleRowAudit:
    """Bundle partition forced by one constant-section triangular row."""

    side: str
    left_color: Color
    right_color: Color
    output_left_color: Color
    output_right_color: Color
    constant_map: Tuple[Tuple[FibrePoint, FibrePoint], ...]
    bundle_fibres: Tuple[TriangularBundleFibre, ...]
    companion_sections_injective: bool

    @property
    def constant_outputs(self) -> Tuple[FibrePoint, ...]:
        return tuple(output for _source, output in self.constant_map)

    @property
    def constant_map_surjective(self) -> bool:
        codomain = (
            {fibre.output_value for fibre in self.bundle_fibres}
            if self.bundle_fibres
            else set()
        )
        return set(self.constant_outputs) == codomain

    @property
    def constant_map_is_bijective(self) -> bool:
        return self.constant_map_surjective and len(set(self.constant_outputs)) == len(
            self.constant_outputs
        )

    @property
    def all_bundle_fibres_partition(self) -> bool:
        return all(fibre.blocks_partition_companion_codomain for fibre in self.bundle_fibres)

    @property
    def bundle_partition_identity_holds(self) -> bool:
        return (
            self.constant_map_surjective
            and self.companion_sections_injective
            and self.all_bundle_fibres_partition
        )

    @property
    def nontrivial_bundle_fibres(self) -> Tuple[TriangularBundleFibre, ...]:
        return tuple(fibre for fibre in self.bundle_fibres if len(fibre.source_inputs) > 1)


