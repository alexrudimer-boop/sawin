@dataclass(frozen=True)
class SectionRankProfileRow:
    """Rank and kernel profile for one coordinate section."""

    side: str
    left_color: Color
    right_color: Color
    output_left_color: Color
    output_right_color: Color
    fixed_input: FibrePoint
    domain_size: int
    codomain_size: int
    rank: int
    kernel_blocks: Tuple[Tuple[FibrePoint, ...], ...]
    image: Tuple[FibrePoint, ...]

    @property
    def kernel_block_sizes(self) -> Tuple[int, ...]:
        return tuple(len(block) for block in self.kernel_blocks)

    @property
    def kernel_kind(self) -> str:
        if all(size == 1 for size in self.kernel_block_sizes):
            return "equality"
        if len(self.kernel_blocks) == 1:
            return "universal"
        return "proper"

    @property
    def is_injective(self) -> bool:
        return self.kernel_kind == "equality"

    @property
    def is_surjective(self) -> bool:
        return self.rank == self.codomain_size

    @property
    def is_bijective(self) -> bool:
        return self.is_injective and self.is_surjective

    @property
    def is_constant(self) -> bool:
        return self.rank == 1

    @property
    def has_proper_nontrivial_kernel(self) -> bool:
        return self.kernel_kind == "proper"

    @property
    def is_injective_non_surjective(self) -> bool:
        return self.is_injective and not self.is_surjective


